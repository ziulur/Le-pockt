// ROM demo: desenha um quadrado (sprite) que se move com o D-pad, fundo xadrez
const fs=require('fs');
const rom=new Uint8Array(0x8000); let p;
const put=(...b)=>{for(const x of b) rom[p++]=x;};
'DEMO LE'.split('').forEach((c,i)=>rom[0x134+i]=c.charCodeAt(0)); rom[0x147]=0x03; rom[0x149]=2; rom[0x143]=0x80;
p=0x100; put(0xC3,0x50,0x01);
p=0x150;
put(0xF3,0x31,0xFE,0xFF);
put(0x3E,0x00,0xE0,0x40); // LCD off
// CGB palettes: bg pal0 colors
put(0x3E,0x80,0xE0,0x68);
for (const c of [0x7FFF,0x5294,0x7C1F,0x0000]) put(0x3E,c&0xFF,0xE0,0x69,0x3E,c>>8,0xE0,0x69);
put(0x3E,0x80,0xE0,0x6A);
for (const c of [0x0000,0x03E0,0x001F,0x7C00]) put(0x3E,c&0xFF,0xE0,0x6B,0x3E,c>>8,0xE0,0x6B);
// tile1 checker (8010..801F) alternate 0xAA/0x55 lo, hi
put(0x21,0x10,0x80,0x06,0x08); let l=p; put(0x3E,0xF0,0x22,0x3E,0x0F,0x22,0x05,0x20); put((l-(p+1))&0xFF);
// tile2 solid ci=1 (8020)
put(0x21,0x20,0x80,0x06,0x08); l=p; put(0x3E,0xFF,0x22,0xAF,0x22,0x05,0x20); put((l-(p+1))&0xFF);
// fill map 9800-9BFF with 1
put(0x21,0x00,0x98,0x01,0x00,0x04); l=p; put(0x3E,0x01,0x22,0x0B,0x78,0xB1,0x20); put((l-(p+1))&0xFF);
// clear OAM, sprite0 at (80,72) tile2
put(0x21,0x00,0xFE,0x06,0xA0,0xAF); l=p; put(0x22,0x05,0x20); put((l-(p+1))&0xFF);
put(0x3E,72+16,0xEA,0x00,0xFE,0x3E,80+8,0xEA,0x01,0xFE,0x3E,0x02,0xEA,0x02,0xFE);
put(0x3E,0xE4,0xE0,0x47,0x3E,0xE4,0xE0,0x48);
put(0x3E,0x93,0xE0,0x40); // LCD on BG+OBJ
put(0x3E,0x01,0xE0,0xFF,0xFB);
const main=p;
put(0x76,0x00);
// read dpad
put(0x3E,0x20,0xE0,0x00,0xF0,0x00,0xF0,0x00,0x2F,0xE6,0x0F,0x47);  // B = dirs pressed (bit0 R,1 L,2 U,3 D)
for (const [bit,addr,op] of [[0,0x01,0x34],[1,0x01,0x35],[2,0x00,0x35],[3,0x00,0x34]]) put(0xCB,0x40|(bit<<3),0x28,0x04,0x21,addr,0xFE,op);
// A button -> write counter to SRAM (battery)
put(0x3E,0x10,0xE0,0x00,0xF0,0x00,0xF0,0x00,0x2F,0xE6,0x01,0x28,0x0A, 0x3E,0x0A,0xEA,0x00,0x00, 0x21,0x00,0xA0,0x34,0x00);
put(0xC3,main&0xFF,main>>8);
p=0x40; put(0xD9);
fs.writeFileSync('demo.gb',rom);
